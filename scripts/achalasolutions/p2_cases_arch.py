def case_arch(case_id):
    """Return (lanes, nodes, edges) or None."""
    spec = CASE_ARCHS.get(case_id)
    if not spec:
        return None
    lanes, node_specs, edge_specs = spec
    # normalize: drop stray bare strings (defensive)
    node_specs = [n for n in node_specs if isinstance(n, tuple)]
    id_map = {}
    nodes = []
    counts = {}
    for i, (role, lane, label, *rest) in enumerate(node_specs):
        hot = bool(rest and rest[0])
        k = counts.get(role, 0)
        counts[role] = k + 1
        nid = f"{role}{k}"
        id_map[i] = nid
        nodes.append({"id": nid, "lane": lane, "label": label, "hot": hot})
    edges = [{"a": id_map[a], "b": id_map[b]} for a, b in edge_specs if a in id_map and b in id_map]
    return lanes, nodes, edges
